"""Цепочка шагов и тексты задач для агентов.

Шаги идут по порядку: сфера → конкуренты → анализ → роли → сценарии → как есть → решение.
Здесь только константы и тексты; граф и банк меняет ``project.py``.
"""

from __future__ import annotations

SPHERE, COMPETITOR, ROLE, SCENARIO = "сфера", "конкурент", "роль", "сценарий"
PROBLEM, ASIS, VARIANT, SOLUTION = "проблема", "как есть", "вариант", "решение"
PARTICIPATES = "участвует"
BANK = "knowledge"                       # один банк проекта: записи competitor, fact, requirement

STEPS = [("sphere", "Сфера"), ("competitors", "Конкуренты"), ("analysis", "Анализ"), ("roles", "Роли"),
         ("scenarios", "Сценарии"), ("asis", "Как есть"), ("solution", "Решение")]


def _list(items) -> str:
    items = [str(i) for i in items if i]
    return "; ".join(items) if items else "нет"


# ---------------------------------------------------------------------- исследователи

def competitors(sphere: str, requirements: list[str], known: list[str], rejected: list[str]) -> str:
    return f"""Найди в интернете конкурентов для сферы бизнеса: «{sphere}».

Нужны сайты самих БИЗНЕСОВ, которые оказывают эти услуги или продают эти товары. Например, для «парикмахерская» это сайты
конкретных парикмахерских и салонов красоты, а не инструменты для их создания.
НЕ подходят: конструкторы сайтов и сервисы для их создания, CRM и программы для бизнеса, крупные федеральные сети-гиганты,
маркетплейсы, агрегаторы, каталоги, статьи, блоги, соцсети. Сайт должен открываться.
Найди 5-8 разных бизнесов.
Требования пользователя (учитывай при выборе): {_list(requirements)}.
Уже есть, не повторяй: {_list(known)}.
Пользователь отклонил, не предлагай снова: {_list(rejected)}.

Отправь `report`: на каждый бизнес одна находка: kind="конкурент", title=название бизнеса, description=чем занимается
и что есть на сайте (одно предложение), data={{"url": "адрес главной страницы"}}, sources=[адрес]."""


def analysis(sphere: str, targets: list[tuple[str, str]]) -> str:
    sites = "\n".join(f"- {name}: {url}" for name, url in targets)
    return f"""Проанализируй сайты бизнесов в сфере «{sphere}»:
{sites}

Открой каждый сайт и изучи именно сайт бизнеса: услуги, запись, оплату, личный кабинет, контакты, что можно сделать онлайн.
Выпиши только то, что действительно видно на сайте. Три вида находок:
- kind="роль" — кто участвует в работе бизнеса (клиент, мастер, администратор, внешние системы);
- kind="процесс" — бизнес-процессы, которые видно на сайте (запись, оплата, отмена, напоминания…);
- kind="фича" — заметные возможности сайта.
Для каждой находки: title — коротко (до 8 слов), description — одно предложение, data={{"competitor": "адрес сайта из списка выше"}},
sources=[адрес страницы, где это видно]. Если сайт не открылся, пропусти его.

Отправь `report`."""


# ---------------------------------------------------------------------- помощник

def context(sphere: str, requirements: list[str], competitors_: list[str], facts: list[str]) -> str:
    return (f"Сфера бизнеса: {sphere}.\n"
            f"Требования пользователя: {_list(requirements)}.\n"
            f"Конкуренты: {_list(competitors_)}.\n"
            "Факты из анализа конкурентов (банк знаний):\n" + ("\n".join("- " + f for f in facts) or "- пока нет"))


def roles(ctx: str, known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить роли.
{ctx}

Предложи до 6 ролей: кто участвует в бизнес-процессах этой сферы (люди и внешние системы: «Клиент», «Мастер»,
«Администратор», «Платёжная система»). Опирайся на банк знаний и требования пользователя. Роль — тот, кто что-то делает в процессе.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждая роль — карточка kind="роль", title — название, body — что делает, одно предложение."""


def scenarios(ctx: str, roles_: list[str], known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить сценарии.
{ctx}
Роли: {_list(roles_)}.

Предложи до 6 ключевых сценариев: самые частые и важные ситуации, в которых роли взаимодействуют, от повода до результата
(например, «Клиент записывается на услугу»). Опирайся на банк знаний и требования пользователя.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждый сценарий — карточка kind="сценарий", title — название, body — одно предложение, attrs.usecase — диаграмма
вариантов использования UML этого сценария: {{"system": "название сценария", "cases": [{{"name": "действие", "actors": ["Роль"]}}]}}.
Вариантов использования (cases) 2-5; актёры — ТОЛЬКО названия ролей из списка выше."""


def _scenario(ctx: str, scenario: dict) -> str:
    return (f"{ctx}\nСценарий: {scenario['title']}. {scenario['body']}\n"
            f"Роли сценария: {_list(scenario['roles'])}. Варианты использования: {_list(scenario['cases'])}.")


def problems(ctx: str, scenario: dict, known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить проблемы сценария «как есть».
{_scenario(ctx, scenario)}

Опиши, какие проблемы возникают в этом сценарии СЕЙЧАС в типичном бизнесе этой сферы без автоматизации: где теряются время,
деньги, клиенты, бывают ошибки. Опирайся на банк знаний (особенно на то, что делают конкуренты) и требования пользователя.
Предложи до 6 самых существенных проблем, которые стоит автоматизировать.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждая проблема — карточка kind="проблема", title — коротко, body — что не так, как часто бывает и чем это стоит,
attrs.importance — одно из: низкая, средняя, высокая, критическая."""


DIAGRAM_FORMAT = """attrs.diagram — диаграмма последовательности UML:
{"participants": ["Клиент", "Администратор"], "steps": [{"from": "Клиент", "to": "Администратор", "text": "Звонит и просит запись"}]}
Участники — роли (при необходимости добавь внешних). Шаги идут по порядку сверху вниз, каждый — сообщение «кто → кому: что»,
6-12 шагов."""


def asis(ctx: str, scenario: dict, problems_: list[str]) -> str:
    return f"""ЗАДАЧА: построить диаграмму «как есть».
{_scenario(ctx, scenario)}
Принятые проблемы сценария: {_list(problems_)}.

Опиши по шагам, как этот сценарий проходит СЕЙЧАС, без автоматизации. Шаги должны показывать места, где возникают принятые проблемы:
у такого шага добавь поле pain: {{"what": "название проблемы"}}.
Одна карточка kind="как есть", title="Как есть: <название сценария>", body — главная проблема процесса, одно предложение.
{DIAGRAM_FORMAT}"""


def variants(ctx: str, scenario: dict, problem: dict, asis_text: str, known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить варианты автоматизации — решения ОДНОЙ проблемы.
{_scenario(ctx, scenario)}
Проблема: {problem['title']}. {problem['body']}
Как есть сейчас:
{asis_text or 'диаграмма ещё не построена'}

Предложи 2-3 разных способа решить именно эту проблему автоматизацией (например: запись на сайте, бот в мессенджере,
интеграция с внешним сервисом; можно автоматизировать не весь процесс, а отдельные шаги). Учитывай требования пользователя.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждый вариант — карточка kind="вариант", title — что автоматизируем, body — как это решает проблему и что для этого нужно."""


def solution(ctx: str, scenario: dict, solved: list[dict], unsolved: list[str], asis_text: str) -> str:
    pairs = "\n".join(f"- Проблема «{s['problem']}» → решение: {s['title']}. {s['body']}" for s in solved)
    return f"""ЗАДАЧА: построить диаграмму «решение» (как будет).
{_scenario(ctx, scenario)}
Выбранные решения проблем:
{pairs}
Проблемы без решения (оставь их в процессе как есть): {_list(unsolved)}.
Как есть сейчас:
{asis_text or 'не описано'}

Опиши по шагам, как этот сценарий будет проходить после внедрения выбранных решений. Добавь участника «Система» (или своё название).
Меняй только шаги, к которым относятся выбранные решения; остальное оставь неизменным. У каждого шага поле mark:
"" — без изменений, "new" — новый шаг, "changed" — изменён, "auto" — теперь выполняется системой автоматически,
"removed" — шаг убран (оставь его в списке с этой отметкой).
Одна карточка kind="решение", title="Решение: <название сценария>", body — что автоматизируем и что получим, 2-3 предложения.
{DIAGRAM_FORMAT}"""


