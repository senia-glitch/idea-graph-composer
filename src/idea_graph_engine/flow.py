def consistency(sphere: str, bounds_: list[str], graph_text: str, issues: list[str], decided: list[tuple[str, str]], auto: bool = False) -> str:
    walls = "\n".join("- " + b for b in bounds_) or "- не заданы"
    found = "\n".join(f"{n}. {text}" for n, text in enumerate(issues, 1)) or "проверка кодом ничего не нашла"
    done = "\n".join(f"- {q} → {a}" for q, a in decided) or "пока нет"
    must = ("ОБЯЗАТЕЛЬНО исправь каждый пункт правками, пока список не станет пустым" if auto
            else "каждый пункт ОБЯЗАТЕЛЬНО нужно разрешить вопросом человеку, пока список не станет пустым")
    ending = """Человека рядом нет, вопросов не задавай: исправь всё сам ОДНИМ вызовом `resolve` со списком правок fixes. Правила:
- карточка выходит за границы системы или противоречит им — remove (спорное тоже убирай, а не оставляй);
- две карточки противоречат друг другу — remove той, что хуже соответствует границам; если равны — той, что создана позже (id с большим номером);
- принятая проблема без решения: есть предложенные варианты — choose_variant лучшего в границах; вариантов нет — suggest_variants;
  ни один не подходит в границах — remove проблемы;
- карточка без описания или важности: edit (описание до 250 символов, важность) по смыслу названия; не получается или вне границ — remove;
- диаграммы нет или она устарела — rebuild сценария (после остальных правок);
- каждый id — только из графа. Ничего не осталось — `finish`.""" if auto else \
        "Задай человеку ОДИН вопрос (`conflict`) про самое важное разногласие и закончи ход. Вопрос — до 120 символов, про одно, варианты — до 60."
    return f"""ЗАДАЧА: проверить согласованность проекта перед выгрузкой документации.
Сфера бизнеса: {sphere}.
Границы системы (человек задал сам, это жёсткое правило):
{walls}

ГРАФ ПРОЕКТА (в скобках id карточек для правок):
{graph_text}

Найдено проверкой кодом ({must}):
{found}

Уже сделано в этой проверке (не повторяй): {done}

Найди ещё разногласия, которых код не видит:
- карточка (сценарий, проблема, решение, шаг «как будет») противоречит границам системы или выходит за них;
- решения разных проблем или сценариев противоречат друг другу (несовместимые способы, дубли, разные системы для одного и того же);
- роли и сценарии не сходятся по смыслу; диаграммы «как есть» и «как будет» не соответствуют принятым проблемам и выбранным решениям.
Не придирайся к мелочам и не выдумывай: разногласие — только то, что ты можешь указать в графе конкретно. Ничего нет — вызови `finish`.
{ending}"""
