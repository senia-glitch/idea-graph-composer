def context(sphere: str, requirements: list[str], competitors_: list[str], facts: list[str], boundaries: list[str] | None = None,
            built: list[str] | None = None) -> str:
    done = ("Уже построено в проекте (учитывай: не дублируй, не противоречь, для общих проблем бери согласованные решения):\n"
            + "\n".join("- " + b for b in built) + "\n") if built else ""
    walls = ("Границы системы — ЖЁСТКОЕ ПРАВИЛО, человек уже решил это сам. Всё, что выходит за них или противоречит им "
             "(процессы, каналы, интеграции, функции, роли), не предлагай и не принимай:\n"
             + "\n".join("- " + b for b in boundaries) + "\n") if boundaries else ""
    return (f"Сфера бизнеса: {sphere}.\n{walls}{done}"
            f"Требования пользователя: {_list(requirements)}.\n"
            f"Конкуренты: {_list(competitors_)}.\n"
            "Факты из анализа конкурентов (банк знаний):\n" + ("\n".join("- " + f for f in facts) or "- пока нет"))


def roles(ctx: str, known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить роли.
{ctx}

Предложи до 6 ролей: кто участвует в бизнес-процессах этой сферы (люди и внешние системы: «Клиент», «Мастер»,
«Администратор», «Платёжная система»). Опирайся на банк знаний и требования пользователя. Роль — тот, кто что-то делает в процессе.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждая роль — карточка kind="роль", title — название, body — что делает, одно предложение."""


def scenarios(ctx: str, roles_: list[str], known: list[str], rejected: list[str]) -> str:
    return f"""ЗАДАЧА: предложить сценарии.
{ctx}
Роли: {_list(roles_)}.

Предложи до 5 ключевых сценариев: самые частые и важные ситуации, в которых роли взаимодействуют, от повода до результата
(например, «Клиент записывается на услугу»). Опирайся на банк знаний и требования пользователя.
Жёсткие правила, их проверит человек и пакет:
- один сценарий — одна цель одной главной роли; два сценария с одной целью или пересекающиеся — оставь один;
- сценарий целиком внутри границ системы: если границы исключили процесс (например, оплата вне сайта, доставка, дегустация),
  не предлагай его даже отдельным сценарием; перед ответом сверь каждый сценарий с каждой границей;
- не предлагай то, что уже есть в списке ниже, и то, что человек отклонил.
Уже есть, не повторяй: {_list(known)}. Пользователь отклонил, не предлагай снова: {_list(rejected)}.
Каждый сценарий — карточка kind="сценарий", title — название, body — одно предложение, attrs.usecase — диаграмма
вариантов использования UML этого сценария: {{"system": "название сценария", "cases": [{{"name": "действие", "actors": ["Роль"]}}]}}.
Вариантов использования (cases) 2-5; актёры — ТОЛЬКО названия ролей из списка выше."""


